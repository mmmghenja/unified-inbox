#!/usr/bin/env python3
"""Генератор `docs/mcp.md` из набора инструментов самого MCP-сервера (`hub.mcp_server.server`).

    uv run python scripts/gen_mcp_docs.py           # переписать docs/mcp.md
    uv run python scripts/gen_mcp_docs.py --check   # код 1, если файл расходится с сервером (для CI)

Файл руками не правится: список и описания берутся из `tool_names` и из зарегистрированных инструментов,
поэтому новый инструмент попадает в документ без правки списков. Тест `tests/test_mcp_docs.py` и проверка
экспорта витрины сверяют файл с сервером.
"""

from __future__ import annotations

import argparse
import re
import sys
import types
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DOC = REPO / "docs" / "mcp.md"
PROFILE = "all"
# Служебные параметры: их подставляет плагин или хук движка, модель их не заполняет.
HIDDEN_PARAMS = frozenset({"oc_session", "oc_dir", "ext_session", "ext_dir"})
HEADING_RE = re.compile(r"^## `([a-z][a-z0-9_]*)`$", re.MULTILINE)
# Некоторые описания подставляют путь установки (`<venv>/bin/hub-load`): у каждой машины он свой.
INSTALL_PATH_RE = re.compile(r"'?(?:/[^\s'\"`]+)?/bin/(hub[\w-]*)'?")


def tools(profile: str = PROFILE) -> list:
    """Инструменты сервера профиля, по имени. Сборка без клиента: ядро не трогается."""
    from hub.mcp_server.server import build_server, tool_names

    client = types.SimpleNamespace(profile=profile)
    server = build_server(types.SimpleNamespace(client=client))  # type: ignore[arg-type]
    by_name = {t.name: t for t in server._tool_manager.list_tools()}  # noqa: SLF001 — как в `tool_names`
    names = tool_names(profile)
    if set(names) != set(by_name):
        raise SystemExit("tool_names и зарегистрированные инструменты расходятся")
    return [by_name[n] for n in sorted(names)]


def _clean(text: str) -> str:
    """Путь установки в описании заменяется на `<install>/bin/…`: документ не зависит от машины."""
    return INSTALL_PATH_RE.sub(lambda m: f"<install>/bin/{m.group(1)}", text)


def _one_line(text: str) -> str:
    return " ".join(text.split())


def _summary(description: str) -> str:
    text = _one_line(description)
    cut = re.search(r"[.!?:](?:\s|$)", text)
    head = text[: cut.end()].rstrip(" :") if cut else text
    return head if len(head) <= 150 else head[:147].rstrip() + "..."


def _cell(text: str) -> str:
    return _one_line(text).replace("|", "\\|")


def _type(schema: dict) -> str:
    if "enum" in schema:
        return "enum: " + ", ".join(f"`{v}`" for v in schema["enum"])
    if "anyOf" in schema:
        kinds = [_type(s) for s in schema["anyOf"]]
        return " or ".join(k for k in dict.fromkeys(kinds) if k != "null") or "any"
    kind = schema.get("type", "any")
    if kind == "array":
        return f"array of {_type(schema.get('items', {}))}"
    return str(kind)


def _params(tool) -> list[str]:
    props = (tool.parameters or {}).get("properties") or {}
    required = set((tool.parameters or {}).get("required") or [])
    rows = []
    for name, schema in props.items():
        if name in HIDDEN_PARAMS:
            continue
        default = "" if name in required or "default" not in schema else f"`{schema['default']!r}`"
        rows.append(
            f"| `{name}` | {_cell(_type(schema))} | {'yes' if name in required else 'no'} | {default} "
            f"| {_cell(_clean(schema.get('description', '')))} |"
        )
    if not rows:
        return ["No parameters.", ""]
    return ["| Parameter | Type | Required | Default | Description |", "|---|---|---|---|---|", *rows, ""]


def render(profile: str = PROFILE) -> str:
    items = tools(profile)
    out = [
        "# MCP tools",
        "",
        "Generated by `scripts/gen_mcp_docs.py` from the MCP server (`hub.mcp_server.server`). Do not edit by hand:",
        "CI fails when this file drifts from the server.",
        "",
        f"Profile `{profile}`, {len(items)} tools. Tool descriptions are written for the model and are in Russian.",
        "Parameters filled in by engine plugins and hooks (`oc_session`, `oc_dir`, `ext_session`, `ext_dir`)",
        "are omitted.",
        "Trust model, tokens and scopes: [architecture.md](architecture.md#agent-access-mcp-srchubmcp_server).",
        "",
        "| Tool | Summary |",
        "|---|---|",
    ]
    out += [f"| [`{t.name}`](#{t.name}) | {_cell(_summary(_clean(t.description or '')))} |" for t in items]
    out.append("")
    for t in items:
        out += [f"## `{t.name}`", "", *[f"> {line}" for line in _clean(t.description or "").strip().splitlines()], ""]
        out += _params(t)
    text = "\n".join(out).rstrip() + "\n"
    if re.search(r"/home/(?!owner/)|/Users/", text):  # `/home/owner/…` — выдуманный путь из примера
        raise SystemExit("в docs/mcp.md попал абсолютный путь машины: дополните INSTALL_PATH_RE")
    return text


def documented_names(text: str) -> list[str]:
    """Имена инструментов, описанных в тексте документа (заголовки второго уровня)."""
    return HEADING_RE.findall(text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="не писать, а сверить файл с сервером")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        have = DOC.read_text(encoding="utf-8") if DOC.is_file() else ""
        if have != text:
            print("docs/mcp.md расходится с MCP-сервером: uv run python scripts/gen_mcp_docs.py", file=sys.stderr)
            return 1
        print(f"docs/mcp.md: {len(documented_names(text))} инструментов, совпадает с сервером")
        return 0
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(text, encoding="utf-8")
    print(f"docs/mcp.md: {len(documented_names(text))} инструментов")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
