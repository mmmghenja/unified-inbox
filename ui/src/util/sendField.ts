// Владелец 28.09: после отправки (Ctrl+Enter или кнопкой) фокус остаётся в поле и можно сразу набирать следующее.
// Поэтому поле очищается в момент отправки, а не после ответа ядра. Не ушло — отправленное возвращается:
// поле пустое — как было; успел набрать новое — отправленное встаёт перед ним (ничего не теряется).

/** Текст поля после неудачной отправки `sent`, если сейчас в поле `current`. */
export function restoreUnsent(current: string, sent: string): string {
  if (current.trim() === '') return sent;
  return `${sent}\n${current}`;
}
