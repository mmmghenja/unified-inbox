-- F1 критика куска 1c (docs/architecture.md): ложное «найдено в истории» после abandon/temporary
-- глушило непосланное сообщение как посланное (нашло СВОЁ ЖЕ прежнее «+» с тем же текстом). `maybe_sent` —
-- единственный источник правды «а мог ли этот лиз реально уйти»: ставится в 1 ТОЛЬКО в ветке истёкшего лиза
-- `outbox.lease()` (строка была в 'sending', лиз кончился без report — падение, abandon, таймаут каркаса) и
-- НЕ сбрасывается ничем, кроме перехода в 'sent'. Коннектор ищет в истории ПЕРЕД отправкой только когда
-- `maybe_sent=1` — после честного temporary/flood (запрос точно не уходил) поиск не нужен и вреден.
ALTER TABLE outbox ADD COLUMN maybe_sent INTEGER NOT NULL DEFAULT 0;
