-- `ui` — владелец из окна сессии или ответом по карточке из интерфейса; `agent` — его агент ответом по карточке
-- `turn` из канала. Карточка `turn` после хода с доставленной `ui`-репликой заводится всегда, после хода по
-- `agent`-реплике — только по явной строке «ВЛАДЕЛЬЦУ:» (без петли «агент ↔ сессия»). Оба файла (`held_say` живёт
-- в файле строк сессии).
ALTER TABLE held_say ADD COLUMN source TEXT NOT NULL DEFAULT 'ui' CHECK (source IN ('ui', 'agent'));
