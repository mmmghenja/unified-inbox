-- Догон ко времени не уходит, если в беседе ответили (Ф30-2, docs/architecture.md,
-- решения 1–3 и поправки П1–П4). Обе схемы.
--
-- `cancel_if_reply` — флажок черновика с `send_at_ts` (`hub_draft(send_at=…, cancel_if_reply=True)`): перед
-- выдачей `lease` (после FIFO) проверяет, был ли в беседе ответ после подтверждения владельца (чужое сообщение,
-- владельца с телефона или из UI; письма хаба от сессий `origin='api'` — не ответ), и тогда строка не уходит
-- (`failed` / `unknown` при `maybe_sent`, причина «догон не ушёл»). Без `send_at_ts` флажок не действует
-- («Отправить сейчас» и «Повторить» обнуляют время). 0 — обычная строка (все старые строки).
ALTER TABLE outbox ADD COLUMN cancel_if_reply INTEGER NOT NULL DEFAULT 0;
