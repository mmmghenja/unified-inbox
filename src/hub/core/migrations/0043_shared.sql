-- Обе схемы.
--
-- `send_at_ts` — время (мс UTC), к которому сессия попросила отправить черновик (`hub_draft(send_at=…)`).
-- Подтверждение владельца ставит строку в `queued` с `not_before_ts = max(send_at_ts, сейчас)`; `lease` позже
-- `send_at_ts + 2 ч` её не выдаёт (`failed send_at_late` / `unknown`). Пока время впереди, подтверждённая
-- строка беседу не держит (П1: ответ владельца в ту же беседу уходит сразу). «Отправить сейчас» и «Повторить»
-- обнуляют колонку — дальше обычная отправка. NULL — обычная строка (все старые строки).
